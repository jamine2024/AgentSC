const dictionaries: Record<Locale, Record<string, string>> = {
  'zh-CN': zh,
  en,
}

const I18nContext = createContext<I18nContextType>({
  locale: 'zh-CN',
  setLocale: () => {},
  t: (key: string) => key,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    const stored = localStorage.getItem('agentsc-locale') as Locale | null
    if (stored === 'zh-CN' || stored === 'en') return stored
    return 'zh-CN'
  })

  useEffect(() => {
    localStorage.setItem('agentsc-locale', locale)
    document.documentElement.lang = locale
  }, [locale])

  const t = useCallback(
    (key: string, params?: Record<string, string | number>, fallback?: string): string => {
      let str = dictionaries[locale]?.[key] ?? fallback ?? key
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
        }
      }
      return str
    },
    [locale],
  )

  const setLocale = useCallback((l: Locale) => setLocaleState(l), [])

  const ctxValue = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])

  return (
    <I18nContext.Provider value={ctxValue}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
