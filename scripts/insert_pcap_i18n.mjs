function insert(block, anchor) {
  const idx = s.lastIndexOf(anchor)
  if (idx === -1) throw new Error('anchor not found: ' + anchor)
  const insertAt = idx + anchor.length
  s = s.slice(0, insertAt) + block + s.slice(insertAt)
}

